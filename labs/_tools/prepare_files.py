def reverse_percentage(after: float, pct: float) -> tuple[float, float]:
    """Price before a discount of pct percent; the second value is the classic wrong answer."""
    return after / (1 - pct / 100), after * (1 + pct / 100)


def weighted(w1: float, s1: float, s2: float) -> tuple[float, float]:
    return (w1 * s1 + (100 - w1) * s2) / 100, (s1 + s2) / 2


def percent_change(old: float, new: float) -> tuple[float, float]:
    return (new - old) / old * 100, (new - old) / new * 100


def up_then_down(start: float, pct: float) -> tuple[float, float]:
    return start * (1 + pct / 100) * (1 - pct / 100), start


