def answer_mode(k: str) -> str:
    p = PROBLEMS[k]
    if p["kind"] == "reverse":
        after, pct = p["args"]
        body = [f"السعر بعد الخصم يساوي {100 - pct}% من السعر الأصلي.",
                f"السعر الأصلي = {after} ÷ {num((100 - pct) / 100)} = {num(p['answer'])} ريالًا.",
                f"الإجابة: {num(p['answer'])} ريالًا."]
    elif p["kind"] == "change":
        old, new = p["args"]
        body = [f"الزيادة = {new} − {old} = {new - old}.",
                f"نسبة الزيادة = {new - old} ÷ {old} = {num(p['answer'])}%.",
                f"الإجابة: {num(p['answer'])}%."]
    else:
        w, s1, s2 = p["args"]
        body = [f"الدرجة = ({w}% × {s1}) + ({100 - w}% × {s2})",
                f"= {num(w * s1 / 100)} + {num((100 - w) * s2 / 100)} = {num(p['answer'])}.",
                f"الإجابة: {num(p['answer'])} درجة."]
    return "\n".join([
        f"سجل تفاعل جاهز · «قبس» في وضع الإجابة · المسألة {NAMES[k]}",
        "(سجل اصطناعي. اقرأه كما يقرؤه طالب طلب الحل ونسخه.)", "",
        f"المتعلم: {p['text']} أعطني الحل.", "",
        "قبس: " + "\n".join(body), "",
        "المتعلم: شكرًا.", ""])


